const CODEX_HOOKS: [HookWiring; 8] = [
    HookWiring {
        event: "SessionStart",
        command: "lgtm hook session-start --adapter codex",
        matcher: None,
    },
    HookWiring {
        event: "UserPromptSubmit",
        command: "lgtm hook user-prompt-submit --adapter codex",
        matcher: None,
    },
    HookWiring {
        event: "PreToolUse",
        command: "lgtm hook pre-tool-use --adapter codex",
        matcher: Some("^(apply_patch|Edit|Write|exec_command|unified_exec|Bash)$"),
    },
    HookWiring {
        event: "PermissionRequest",
        command: "lgtm hook permission-request --adapter codex",
        matcher: Some("^(apply_patch|Edit|Write|exec_command|unified_exec|Bash)$"),
    },
    HookWiring {
        event: "SubagentStart",
        command: "lgtm hook subagent-start --adapter codex",
        matcher: None,
    },
    HookWiring {
        event: "SubagentStop",
        command: "lgtm hook subagent-stop --adapter codex",
        matcher: None,
    },
    HookWiring {
        event: "PostToolUse",
        command: "lgtm hook post-tool-use --adapter codex",
        matcher: Some("^(apply_patch|Edit|Write|exec_command|unified_exec|Bash)$"),
    },
    HookWiring {
        event: "Stop",
        command: "lgtm hook stop --adapter codex",
        matcher: None,
    },
];

struct HookWiring {
    event: &'static str,
    command: &'static str,
    matcher: Option<&'static str>,
}

pub(super) fn render_hooks(validated: ValidatedSettings) -> Option<Vec<u8>> {
    let existing = validated.unwrap_or_default();
    let binary = hook_binary();
    let merged = merge_hooks_with_binary(&existing, &binary);
    if merged == existing {
        return None;
    }
    let mut serialized = serde_json::to_string_pretty(&Value::Object(merged))
        .expect("Codex hooks map serializes as a JSON object");
    serialized.push('\n');
    Some(serialized.into_bytes())
}

pub(super) fn refresh_existing_hooks(existing: &Map<String, Value>) -> Map<String, Value> {
    let mut refreshed = existing.clone();
    if let Some(hooks) = refreshed.get_mut("hooks").and_then(Value::as_object_mut) {
        for wiring in &CODEX_HOOKS {
            if let Some(entries) = hooks.get_mut(wiring.event).and_then(Value::as_array_mut) {
                for entry in entries
                    .iter_mut()
                    .filter(|entry| entry_runs_command(entry, wiring.command))
                {
                    reconcile_matcher(entry, wiring.matcher);
                }
            }
        }
    }
    refreshed
}

#[cfg(test)]
pub(super) fn merge_hooks(existing: &Map<String, Value>) -> Map<String, Value> {
    merge_hooks_with_binary(existing, "lgtm")
}

fn merge_hooks_with_binary(existing: &Map<String, Value>, binary: &str) -> Map<String, Value> {
    let mut merged = existing.clone();
    let hooks_entry = merged
        .entry("hooks")
        .or_insert_with(|| Value::Object(Map::new()));
    let Value::Object(hooks) = hooks_entry else {
        return merged;
    };
    for wiring in &CODEX_HOOKS {
        let entries = hooks
            .entry(wiring.event.to_string())
            .or_insert_with(|| Value::Array(Vec::new()));
        let Value::Array(entries) = entries else {
            continue;
        };
        match entries
            .iter_mut()
            .find(|entry| entry_runs_command(entry, wiring.command))
        {
            Some(entry) => reconcile_matcher(entry, wiring.matcher),
            None => entries.push(hook_entry(wiring, binary)),
        }
    }
    merged
}

/// First line of every lgtm-generated Codex rules file.
///
/// Doubles as the retirement marker: a file starting with it was written by
/// lgtm and is replaced with an inert comment-only file, while anything else
/// belongs to the user and is preserved.
const GENERATED_HEADER: &str = "# Generated by lgtm from .lgtm/execpolicy.json\n";

/// Retire lgtm-generated Codex command bans from a rules file.
///
/// LGTM no longer compiles `.lgtm/execpolicy.json` into Codex `prefix_rule`
/// bans, so no run emits a forbidden, prompt, or allow rule. `contents` and
/// `source_path` no longer govern Codex permissions and are accepted only for
/// the current init and managed-refresh callers; a malformed legacy policy is
/// ignored instead of failing init.
///
/// Rules lgtm generated earlier are cleared on a normal init or managed
/// refresh, while files it does not own are preserved:
///
/// - no rules file, a symlink, an unreadable file, or a file without the
///   generated header: no write;
/// - a header-marked file lgtm generated: an inert comment-only replacement;
/// - that replacement already in place: no write, so planning is idempotent.
pub(super) fn render_execpolicy(
    _source_path: &Path,
    _contents: &str,
    rules_path: &Path,
) -> Result<(Option<Vec<u8>>, Vec<String>), InitError> {
    plan_retired_rules(rules_path)
}

fn plan_retired_rules(rules_path: &Path) -> Result<(Option<Vec<u8>>, Vec<String>), InitError> {
    let Ok(metadata) = std::fs::symlink_metadata(rules_path) else {
        return Ok((None, Vec::new()));
    };
    if metadata.file_type().is_symlink() {
        return Ok((
            None,
            vec![format!(
                "preserving {}; it is a symlink and lgtm does not write through it",
                rules_path.display()
            )],
        ));
    }
    // Keep the bounded, nonblocking regular-file checks on every caller path.
    let Some(existing) = super::read_if_exists(rules_path)? else {
        return Ok((None, Vec::new()));
    };
    if !existing.starts_with(GENERATED_HEADER) {
        return Ok((
            None,
            vec![format!(
                "preserving existing {}; it was not generated by lgtm",
                rules_path.display()
            )],
        ));
    }
    let retired = retired_rules_content();
    if existing == retired {
        return Ok((None, Vec::new()));
    }
    Ok((
        Some(retired.into_bytes()),
        vec![format!(
            "cleared retired lgtm-generated Codex command bans in {}; lgtm no longer writes Codex rules",
            rules_path.display()
        )],
    ))
}

/// Inert comment-only replacement for a rules file lgtm generated before
/// Codex command bans were retired.
///
/// It repeats [`GENERATED_HEADER`] so later runs still see the file as
/// lgtm-owned and then detect that the replacement is already in place.
fn retired_rules_content() -> String {
    format!(
        "{GENERATED_HEADER}# lgtm no longer writes Codex command bans; use `lgtm check` or CI for policy checks\n"
    )
}

/// Report whether Codex's external config appears to contain a trust record
/// for this project's hook file. This is intentionally advisory: LGTM never
/// writes Codex's private trust state or treats a stale hash as trusted.
pub(super) fn trust_note(hooks_path: &Path) -> String {
    let Some(home) = std::env::var_os("CODEX_HOME")
        .map(std::path::PathBuf::from)
        .or_else(|| {
            std::env::var_os("HOME").map(|home| std::path::PathBuf::from(home).join(".codex"))
        })
    else {
        return codex_trust_note("trust state unavailable; review `/hooks`");
    };
    let config = home.join("config.toml");
    let Ok(metadata) = std::fs::metadata(&config) else {
        return codex_trust_note("no trust record detected; review `/hooks`");
    };
    if metadata.len() > 512 * 1_024 {
        return codex_trust_note("trust config too large to inspect; review `/hooks`");
    }
    let Ok(contents) = std::fs::read_to_string(config) else {
        return codex_trust_note("trust state unreadable; review `/hooks`");
    };
    let path = hooks_path.to_string_lossy();
    let has_record = contents.contains(path.as_ref()) && contents.contains("trusted_hash");
    if has_record {
        codex_trust_note("existing trust record detected; verify it in `/hooks`")
    } else {
        codex_trust_note("no matching trust record detected; review `/hooks`")
    }
}

fn codex_trust_note(status: &str) -> String {
    format!(
        "Codex SHA-256-pins hook definitions; {status}. Trust state is managed by Codex outside this repository and is not auto-approved by init."
    )
}

fn entry_runs_command(entry: &Value, expected: &str) -> bool {
    entry
        .get("hooks")
        .and_then(Value::as_array)
        .is_some_and(|hooks| {
            hooks.iter().any(|hook| {
                hook.get("type").and_then(Value::as_str) == Some("command")
                    && hook
                        .get("command")
                        .and_then(Value::as_str)
                        .is_some_and(|found| commands_match(found, expected))
            })
        })
}

fn reconcile_matcher(entry: &mut Value, matcher: Option<&str>) {
    let Value::Object(entry) = entry else {
        return;
    };
    match matcher {
        Some(matcher) => {
            entry.insert("matcher".to_string(), Value::String(matcher.to_string()));
        }
        None => {
            entry.remove("matcher");
        }
    }
}

fn hook_entry(wiring: &HookWiring, binary: &str) -> Value {
    let inner = json!({
        "type": "command",
        "command": format!("{binary} {}", wiring.command.trim_start_matches("lgtm ")),
    });
    match wiring.matcher {
        Some(matcher) => json!({ "matcher": matcher, "hooks": [inner] }),
        None => json!({ "hooks": [inner] }),
    }
}

pub(super) fn hook_binary() -> String {
    if let Some(binary) = std::env::var_os("LGTM_HOOK_BINARY") {
        return binary.to_string_lossy().into_owned();
    }
    let Ok(path) = std::env::current_exe() else {
        return "lgtm".to_string();
    };
    if !path.is_absolute()
        || path
            .components()
            .any(|component| component == Component::Normal("target".as_ref()))
    {
        return "lgtm".to_string();
    }
    shlex::try_quote(&path.to_string_lossy())
        .map(|quoted| quoted.into_owned())
        .unwrap_or_else(|_| "lgtm".to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn merge_adds_all_codex_events_and_matchers() {
        let merged = merge_hooks(&Map::new());
        let hooks = merged["hooks"].as_object().expect("hooks object");
        assert_eq!(hooks.len(), 8);
        assert_eq!(
            hooks["PreToolUse"][0]["matcher"],
            "^(apply_patch|Edit|Write|exec_command|unified_exec|Bash)$"
        );
        assert_eq!(
            hooks["PreToolUse"][0]["hooks"][0]["command"],
            "lgtm hook pre-tool-use --adapter codex"
        );
    }

    #[test]
    fn merge_is_idempotent_and_preserves_unrelated_values() {
        let existing = json!({
            "permissions": {"allow": ["Bash"]},
            "hooks": {
                "Stop": [{"hooks": [{"type": "command", "command": "other"}]}]
            }
        });
        let existing = existing.as_object().expect("object").clone();
        let once = merge_hooks(&existing);
        let twice = merge_hooks(&once);
        assert_eq!(once, twice);
        assert_eq!(once["permissions"], json!({"allow": ["Bash"]}));
        assert_eq!(once["hooks"]["Stop"].as_array().unwrap().len(), 2);
    }

    #[test]
    fn merge_reconciles_path_qualified_lgtm_matcher() {
        let existing = json!({
            "hooks": {
                "PreToolUse": [{
                    "matcher": "Bash",
                    "hooks": [{
                        "type": "command",
                        "command": "/usr/local/bin/lgtm hook pre-tool-use --adapter codex"
                    }]
                }]
            }
        });
        let merged = merge_hooks(existing.as_object().expect("object"));
        assert_eq!(
            merged["hooks"]["PreToolUse"][0]["matcher"],
            "^(apply_patch|Edit|Write|exec_command|unified_exec|Bash)$"
        );
        assert_eq!(merged["hooks"]["PreToolUse"].as_array().unwrap().len(), 1);
    }

    #[test]
    fn hook_entry_can_use_a_stable_absolute_binary() {
        let merged = merge_hooks_with_binary(&Map::new(), "/usr/local/bin/lgtm");
        assert_eq!(
            merged["hooks"]["Stop"][0]["hooks"][0]["command"],
            "/usr/local/bin/lgtm hook stop --adapter codex"
        );
    }

    /// LGTM retires its own Codex bans and leaves every other file alone.
    ///
    /// A fresh path gains no rules, an old generated file becomes inert, a
    /// user-written file stays byte-for-byte unchanged, a symlink is not
    /// followed, and planning is idempotent. Malformed legacy policy text must
    /// not fail or revive the retired compiler.
    #[test]
    fn execpolicy_retires_generated_bans_and_preserves_user_rules() {
        let root =
            std::env::temp_dir().join(format!("lgtm-execpolicy-retired-{}", std::process::id()));
        let rules = root.join(".codex/rules/lgtm.rules");
        std::fs::create_dir_all(rules.parent().expect("rules parent")).expect("rules directory");
        let source = root.join(".lgtm/execpolicy.json");

        let malformed = "{not json";
        let (rendered, notes) =
            render_execpolicy(&source, malformed, &rules).expect("an absent path must not fail");
        assert!(rendered.is_none(), "a fresh path must not gain rules");
        assert!(notes.is_empty(), "no write must produce no note");

        std::fs::write(
            &rules,
            format!(
                "{GENERATED_HEADER}prefix_rule(pattern=[\"rm\",\"-rf\"], decision=\"forbidden\")\n"
            ),
        )
        .expect("stale generated rules");
        let (rendered, notes) = render_execpolicy(&source, malformed, &rules)
            .expect("malformed legacy policy must not fail");
        let rendered =
            String::from_utf8(rendered.expect("a generated file is retired")).expect("UTF-8 rules");
        assert!(
            !rendered.contains("prefix_rule"),
            "the replacement must stay inert: {rendered}"
        );
        assert!(rendered.starts_with(GENERATED_HEADER));
        assert!(notes.iter().any(|note| note.contains("cleared")));

        std::fs::write(&rules, &rendered).expect("inert replacement installed");
        let (rendered, _) =
            render_execpolicy(&source, malformed, &rules).expect("planning must not fail");
        assert!(
            rendered.is_none(),
            "an inert replacement must not be rewritten"
        );

        let authored =
            "# user-owned Codex rules\nprefix_rule(pattern=[\"ls\"], decision=\"allow\")\n";
        std::fs::write(&rules, authored).expect("user rules");
        let (rendered, notes) =
            render_execpolicy(&source, malformed, &rules).expect("planning must not fail");
        assert!(rendered.is_none(), "a user-written file must be preserved");
        assert!(
            notes
                .iter()
                .any(|note| note.contains("not generated by lgtm"))
        );
        assert_eq!(
            std::fs::read_to_string(&rules).expect("user rules readable"),
            authored,
            "a user-written file must stay byte-for-byte unchanged"
        );

        #[cfg(unix)]
        {
            let target = root.join("owner-rules.rules");
            std::fs::write(&target, authored).expect("symlink target");
            std::fs::remove_file(&rules).expect("replace user rules with a symlink");
            std::os::unix::fs::symlink(&target, &rules).expect("symlink rules file");
            let (rendered, notes) =
                render_execpolicy(&source, malformed, &rules).expect("planning must not fail");
            assert!(rendered.is_none(), "a symlink must be preserved");
            assert!(notes.iter().any(|note| note.contains("symlink")));
            assert_eq!(
                std::fs::read_to_string(&target).expect("symlink target readable"),
                authored,
                "a symlink target must stay unchanged"
            );
        }

        let _ = std::fs::remove_dir_all(root);
    }
}
